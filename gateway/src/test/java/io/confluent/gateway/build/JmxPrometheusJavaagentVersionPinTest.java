package io.confluent.gateway.build;

import static org.junit.Assert.assertEquals;

import java.io.IOException;
import java.io.InputStream;
import java.util.Properties;
import org.junit.Test;

/**
 * Pin test for the {@code io.prometheus.jmx:jmx_prometheus_javaagent} dependency bundled by
 * this module (see gateway/pom.xml).
 *
 * <p>The version is NOT pinned in this repo -- it flows straight through, unpinned, from the
 * {@code common} parent POM's {@code jmx_prometheus_javaagent.version} property. That version
 * matters because 1.1.0+ is no longer published to Maven Central; Confluent mirrors the
 * GitHub-release jar into an internal CodeArtifact repo instead (see Jira INIT-18224, Slack
 * #cp_8_4_0_jmx_prometheus_javaagent_upgrade_1_5_0). A bump can silently break builds that
 * lack access to that mirror, and jmx_exporter 1.0.1 also ships breaking changes (metrics
 * move from `/` to `/metrics`, some JVM metric names change, colliding MBeans gain an
 * `_objectname` label) that ripple out to CFK/customers/jmx-monitoring-stacks scraping the
 * exporter port this module bundles.
 *
 * <p>This test pins the CURRENT known-good version. It is deliberately written to FAIL the
 * moment the resolved version changes -- in either direction, to any value -- rather than to
 * check for a specific target. That is the point: a version bump should never land silently.
 * When it's time to bump for real, update {@link #PINNED_VERSION} in the same commit as the
 * bump and treat this test turning red as your reminder to re-review the breaking changes
 * above before merging.
 */
public class JmxPrometheusJavaagentVersionPinTest {

    private static final String PINNED_VERSION = "0.20.0";

    @Test
    public void jmxPrometheusJavaagentVersionMustNotChangeUnnoticed() throws IOException {
        String resolvedVersion = readResolvedVersion();
        assertEquals(
            "jmx_prometheus_javaagent version has changed. If this is an intentional upgrade "
                + "(e.g. CP8.4 / INIT-18224), update PINNED_VERSION in "
                + "JmxPrometheusJavaagentVersionPinTest -- but first confirm: (1) the internal "
                + "CodeArtifact mirror actually has this exact version (1.1.0+ is not on Maven "
                + "Central), and (2) any scrape configs / dashboards that depend on the `/` "
                + "metrics path or old JVM metric names have been updated for the jmx_exporter "
                + "1.0.1+ breaking changes.",
            PINNED_VERSION,
            resolvedVersion);
    }

    private static String readResolvedVersion() throws IOException {
        Properties properties = new Properties();
        try (InputStream in = JmxPrometheusJavaagentVersionPinTest.class
                .getClassLoader()
                .getResourceAsStream("build-versions.properties")) {
            if (in == null) {
                throw new IllegalStateException(
                    "build-versions.properties not found on test classpath -- expected it to be "
                        + "generated by Maven resource filtering from src/test/resources "
                        + "(check <testResources> filtering is enabled in gateway/pom.xml).");
            }
            properties.load(in);
        }
        String version = properties.getProperty("jmx_prometheus_javaagent.version");
        if (version == null || version.startsWith("${")) {
            throw new IllegalStateException(
                "jmx_prometheus_javaagent.version was not resolved by Maven filtering -- got: '"
                    + version + "'. This test must be run via `mvn test` (or `package`), not by "
                    + "invoking the compiled class directly, so filtering has a chance to run.");
        }
        return version;
    }
}
